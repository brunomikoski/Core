#if UNITY_LOCALIZATION_AVAILABLE
using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using System.Text.RegularExpressions;
using UnityEditor;
using UnityEngine;
using UnityEngine.Localization.Tables;

namespace BrunoMikoski.Core.Utils.Localization
{
    public static class LocalizationKeysGenerator
    {
        private const string OutputFileName = "LocalizationKeys.g.cs";
        private const int MaxIdentifierLength = 100;

        [MenuItem("Tools/Localization/Generate Localization Keys", false, 50)]
        public static void Generate()
        {
            LocalizationKeysGeneratorSettings settings = LocalizationKeysGeneratorSettings.Instance;
            if (!settings.IsConfigured())
            {
                Debug.LogWarning("Localization keys generator is not configured. Set the output folder and namespace in Project Settings > Localization Keys.");
                return;
            }

            List<(string TableName, string Key)> entries = CollectAllLocalizationEntries();
            if (entries.Count == 0)
            {
                Debug.LogWarning("No localization entries found. Ensure you have String Table Collections with SharedTableData in your project.");
                return;
            }

            string content = NormalizeLineEndings(BuildGeneratedFileContent(entries, settings.GeneratedScriptNamespace));
            string outputPath = Path.Combine(settings.GeneratedScriptFolder, OutputFileName);

            string directory = Path.GetDirectoryName(outputPath);
            if (!string.IsNullOrEmpty(directory) && !Directory.Exists(directory))
            {
                Directory.CreateDirectory(directory);
            }

            string existingContent = File.Exists(outputPath) ? File.ReadAllText(outputPath) : null;
            if (existingContent != content)
            {
                File.WriteAllText(outputPath, content);
                AssetDatabase.Refresh();
                Debug.Log($"Generated {entries.Count} localization keys at {outputPath}");
            }
            else
            {
                Debug.Log($"Localization keys are up to date ({entries.Count} keys). No changes written.");
            }
        }

        private static List<(string TableName, string Key)> CollectAllLocalizationEntries()
        {
            List<(string, string)> result = new();
            string[] guids = AssetDatabase.FindAssets($"t:{nameof(SharedTableData)}");

            foreach (string guid in guids)
            {
                string path = AssetDatabase.GUIDToAssetPath(guid);
                var sharedData = AssetDatabase.LoadAssetAtPath<SharedTableData>(path);
                if (sharedData == null)
                    continue;

                string tableName = sharedData.TableCollectionName;
                if (string.IsNullOrEmpty(tableName))
                    continue;

                foreach (var entry in sharedData.Entries)
                {
                    if (entry != null && !string.IsNullOrEmpty(entry.Key))
                    {
                        result.Add((tableName, entry.Key));
                    }
                }
            }

            return result;
        }

        private static string BuildGeneratedFileContent(List<(string TableName, string Key)> entries, string generatedNamespace)
        {
            StringBuilder sb = new StringBuilder();

            sb.AppendLine("// <auto-generated>");
            sb.AppendLine("//     This code was generated by a tool.");
            sb.AppendLine("//     Do not edit this file directly.");
            sb.AppendLine("//     To regenerate, use: Tools > Localization > Generate Localization Keys");
            sb.AppendLine("// </auto-generated>");
            sb.AppendLine();
            sb.AppendLine("using UnityEngine.Localization;");
            sb.AppendLine();
            sb.AppendLine($"namespace {generatedNamespace}");
            sb.AppendLine("{");
            sb.AppendLine("    public static class LocalizationKeys");
            sb.AppendLine("    {");

            HashSet<string> usedNames = new(StringComparer.Ordinal);

            foreach (var (tableName, key) in entries.OrderBy(e => e.TableName).ThenBy(e => e.Key))
            {
                string propertyName = ToValidIdentifier(key);
                if (string.IsNullOrEmpty(propertyName))
                    propertyName = "Key";

                if (!char.IsLetter(propertyName[0]) && propertyName[0] != '_')
                    propertyName = "_" + propertyName;

                string uniqueName = propertyName;
                int suffix = 0;
                while (usedNames.Contains(uniqueName))
                {
                    suffix++;
                    uniqueName = propertyName + suffix;
                }
                usedNames.Add(uniqueName);

                string escapedTableName = EscapeString(tableName);
                string escapedKey = EscapeString(key);
                sb.AppendLine($"        public static LocalizedString {uniqueName} = new LocalizedString({escapedTableName}, {escapedKey});");
            }

            sb.AppendLine("    }");
            sb.AppendLine("}");

            return sb.ToString();
        }

        private static string NormalizeLineEndings(string text)
        {
            return text.Replace("\r\n", "\n").Replace("\r", "\n");
        }

        private static string ToValidIdentifier(string key)
        {
            if (string.IsNullOrEmpty(key))
                return string.Empty;

            string sanitized = Regex.Replace(key, @"[^\w\s]", " ");
            sanitized = Regex.Replace(sanitized, @"\s+", " ");
            sanitized = sanitized.Trim();

            string[] parts = sanitized.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
            if (parts.Length == 0)
                return "KEY";

            StringBuilder result = new StringBuilder();
            foreach (string part in parts)
            {
                if (part.Length == 0)
                    continue;

                string word = part.ToUpperInvariant();
                string segment = result.Length == 0 ? word : "_" + word;

                if (result.Length + segment.Length > MaxIdentifierLength)
                    break;

                result.Append(segment);
            }

            string identifier = result.ToString();
            return string.IsNullOrEmpty(identifier) ? "KEY" : identifier;
        }

        private static string EscapeString(string value)
        {
            if (value == null)
                return "\"\"";

            return "\"" + value
                .Replace("\\", "\\\\")
                .Replace("\"", "\\\"")
                .Replace("\n", "\\n")
                .Replace("\r", "\\r")
                .Replace("\t", "\\t") + "\"";
        }
    }
}
#endif
